// certificate tables for Theorem OE-low, 14 <= N <= 78 (exact integers).
// usage: gen NLO NHI MODNAME OUTFILE
use std::env; use std::fs::File; use std::io::Write;
fn gcd(a:u64,b:u64)->u64{ if b==0 {a} else {gcd(b,a%b)} }
fn ok(r:u64,w:u64,d:u64)->bool{ w%d!=0 && w%d!=r%d && (w+r)%d!=0 }
fn main(){
    let a:Vec<String>=env::args().collect();
    let nlo:u64=a[1].parse().unwrap(); let nhi:u64=a[2].parse().unwrap();
    let modname=&a[3]; let out=&a[4];
    let mut s=String::new();
    s.push_str(&format!("/- GENERATED by the block generator `gen.rs` of the accompanying code, N = {}..{}. Do not edit. -/\nimport LRSpectrumFull.Sext6.Gap.OEFinCore\n\nset_option maxRecDepth 1000000\nset_option maxHeartbeats 0\nset_option Elab.async false\n\nnamespace LRSpectrumFull\nnamespace Sext6\nnamespace Gap\n\n",nlo,nhi));
    let mut stats=String::new();
    for n in nlo..=nhi {
        let mut ents:Vec<String>=vec![]; let mut totw=0u64; let mut maxl=0usize; let mut nexc=0usize;
        for r in 1..=(n/2) {
            // admissible D
            let cand:Vec<u64>=((n+1+r)..=(2*n)).filter(|&d| gcd(d,r)==1).collect();
            // L modulus: D <= 2N-1 minimising Wb
            let mut best:Option<(u64,u64)>=None;
            for &d in cand.iter().filter(|&&d| d<=2*n-1){
                let e=2*n-d; let num=d*n*n; let wb=(num+2*e-1)/(2*e);
                if best.map_or(true,|(_,b)| wb<b){ best=Some((d,wb)); }
            }
            let (d0,wb)=best.expect("no L modulus");
            let mut unc:Vec<u64>=((n+1)..wb).collect();
            let mut ds:Vec<u64>=vec![];
            loop {
                if unc.is_empty(){break;}
                let mut bd=0u64; let mut bc=0usize;
                for &d in &cand { let c=unc.iter().filter(|&&w| ok(r,w,d)).count(); if c>bc {bc=c;bd=d;} }
                if bc==0 {break;}
                ds.push(bd); unc.retain(|&w| !ok(r,w,bd));
            }
            // unc = exceptions
            totw+=wb.saturating_sub(n+1); maxl=maxl.max(ds.len()); nexc+=unc.len();
            let dsl=ds.iter().map(|x|x.to_string()).collect::<Vec<_>>().join(", ");
            let exl=unc.iter().map(|x|x.to_string()).collect::<Vec<_>>().join(", ");
            ents.push(format!("  ⟨{}, [{}], [{}], {}, {}⟩",r,dsl,exl,d0,wb));
        }
        s.push_str(&format!("def tab{} : List Ent := [\n{}]\n\n",n,ents.join(",\n")));
        s.push_str(&format!("/-- N = {} : sum of Wb-N-1 = {}, max |Ds| = {}, exceptions = {}. -/\ntheorem chunk{} : tabOK {} tab{} = true := by decide +kernel\n\n",n,totw,maxl,nexc,n,n,n));
        stats.push_str(&format!("N={} totw={} maxDs={} exc={}\n",n,totw,maxl,nexc));
    }
    s.push_str("end Gap\nend Sext6\nend LRSpectrumFull\n");
    let _=modname;
    File::create(out).unwrap().write_all(s.as_bytes()).unwrap();
    print!("{}",stats);
}
