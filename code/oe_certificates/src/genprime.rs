// block certificate for PrimeWindow7, 79 <= N <= N1.
// usage: genprime N1 OUTFILE
use std::env; use std::fs::File; use std::io::Write;
fn main(){
    let a:Vec<String>=env::args().collect();
    let n1:usize=a[1].parse().unwrap(); let out=&a[2];
    let lim=2*n1+10;
    let mut is=vec![true;lim+1]; is[0]=false; is[1]=false;
    let mut i=2; while i*i<=lim { if is[i]{ let mut j=i*i; while j<=lim {is[j]=false;j+=i;} } i+=1; }
    let mut blocks:Vec<(usize,usize,Vec<usize>)>=vec![];
    let mut lo=79usize;
    while lo<=n1 {
        // seven largest primes <= 2*lo
        let mut ps:Vec<usize>=vec![]; let mut p=2*lo;
        while ps.len()<7 { if is[p]{ps.push(p);} p-=1; }
        ps.reverse(); let pmin=ps[0];
        // max hi with hi+1+hi/2 <= pmin
        let mut hi=lo; while (hi+1)+1+(hi+1)/2<=pmin { hi+=1; }
        assert!(hi>=lo,"block empty at {}",lo);
        blocks.push((lo,hi,ps)); lo=hi+1;
    }
    let mut s=String::new();
    s.push_str(&format!("/- GENERATED by the block generator `genprime.rs` of the accompanying code (N1 = {}). Do not edit.\n   {} blocks; block i: seven primes p in [hi+1+hi/2, 2 lo] settle every N in [lo, hi]. -/\nimport LRSpectrumFull.Sext6.Gap.OEPrimeCore\n\nnamespace LRSpectrumFull\nnamespace Sext6\nnamespace Gap\n\n",n1,blocks.len()));
    for (k,(lo,hi,ps)) in blocks.iter().enumerate() {
        let l=ps.iter().map(|x|x.to_string()).collect::<Vec<_>>().join(", ");
        let alts=vec!["rfl";7].join(" | ");
        s.push_str(&format!("theorem blk{} {{N : ℕ}} (h1 : {} ≤ N) (h2 : N ≤ {}) :\n    7 ≤ ((Finset.Icc (N + 1 + N / 2) (2 * N)).filter Nat.Prime).card :=\n  win7 [{}] (by decide) (by decide)\n    (by intro p hp; simp only [List.mem_cons, List.not_mem_nil, or_false] at hp\n        rcases hp with {} <;> norm_num)\n    (by intro p hp; simp only [List.mem_cons, List.not_mem_nil, or_false] at hp\n        rcases hp with {} <;> omega)\n    (by intro p hp; simp only [List.mem_cons, List.not_mem_nil, or_false] at hp\n        rcases hp with {} <;> omega)\n\n",k,lo,hi,l,alts,alts,alts));
    }
    s.push_str(&format!("theorem primeWindow7_small {{N : ℕ}} (h1 : 79 ≤ N) (h2 : N ≤ {}) : PrimeWindow7 N := by\n  apply window_mono\n",n1));
    for (k,(_lo,hi,_)) in blocks.iter().enumerate() {
        if k+1==blocks.len(){ s.push_str(&format!("  exact blk{} (by omega) (by omega)\n",k)); }
        else { s.push_str(&format!("  by_cases c{} : N ≤ {}\n  · exact blk{} (by omega) c{}\n",k,hi,k,k)); }
    }
    s.push_str("\nend Gap\nend Sext6\nend LRSpectrumFull\n");
    File::create(out).unwrap().write_all(s.as_bytes()).unwrap();
    println!("{} blocks, last hi {}",blocks.len(),blocks.last().unwrap().1);
}
